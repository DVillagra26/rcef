
ic_ui <- function() {
  tagList(
    fluidRow(
      column(4,
        wellPanel(
          h4("Source"),
          radioButtons("ic_source", NULL,
            c("InterCatch exchange format (HI/SI/SD csv)" = "exchange",
              "InterCatch output format (StockOverview txt)" = "output")),
          span(class = "note",
               "Exchange format calls funIntercatchCEF(). Output format ",
               "calls funICoutCEF(), which writes temporary exchange files ",
               "and then calls funIntercatchCEF() itself."),
          tags$hr(),

          h4("Input files"),
          radioButtons("ic_input_mode", NULL,
            c("Folder on this machine" = "path", "Upload files" = "upload")),
          conditionalPanel("input.ic_input_mode == 'path'",
            textInput("ic_path", "dat_path", "./data/data_overviews_format/pok")),
          conditionalPanel("input.ic_input_mode == 'upload'",
            fileInput("ic_files", NULL, multiple = TRUE,
                      accept = c(".csv", ".txt")),
            span(class = "note",
                 "Uploads are copied into a temporary folder laid out the ",
                 "way the functions expect. For the output format that ",
                 "means a sub-folder per year.")),
          conditionalPanel("input.ic_source == 'output'",
            textInput("ic_years", "years (comma separated)", "2022")),
          tags$hr(),

          h4("stock_relation"),
          radioButtons("ic_rel_mode", NULL,
            c("Build with funMakeRelation(year)" = "build",
              "Upload a csv" = "upload",
              "Let funICoutCEF build it" = "auto")),
          conditionalPanel("input.ic_rel_mode == 'build'",
            numericInput("ic_rel_year", "year", 2022, 1990, 2100, 1),
            actionButton("build_rel", "Build stock_relation", class = "btn-sm")),
          conditionalPanel("input.ic_rel_mode == 'upload'",
            fileInput("ic_rel_file", NULL, accept = ".csv")),
          uiOutput("rel_status"))),

      column(4,
        wellPanel(
          h4("Output"),
          checkboxGroupInput("ic_output_format", "output_format",
                             OUTPUT_FORMATS,
                             selected = c("to_list", "to_file")),
          span(class = "note",
               "to_list is what the workbench itself consumes. to_file ",
               "writes the three CEF csv files; to_upload writes the ",
               "comma-separated upload files without headers."),
          textInput("ic_out_path", "out_path", "./data/data_CEF_format"),
          textInput("ic_prefix", "file_prefix", "pok_2022_"),
          textInput("ic_suffix", "file_suffix", "_CEF_v17.1"),
          tags$hr(),
          h4("Options"),
          checkboxInput("ic_incl_bms", "include_BMS_Caton", TRUE),
          checkboxInput("ic_patch_psu", "patch_missing_DIS_PSU", FALSE),
          span(class = "note",
               "patch_missing_DIS_PSU inserts FishingTrip and 0 where a ",
               "discard domain exists with no PSU."),
          checkboxInput("ic_keep_temp", "keep_temp_file (output format only)",
                        FALSE),
          selectInput("ic_metier6", "metier6",
                      c("NULL (MIS_MIS_0_0_0)" = "", "Fleet" = "Fleet")),
          span(class = "note",
               "Fleet copies fleetValue into metier6 and remaps count units ",
               "to NE3."),
          tags$hr(),
          actionButton("run_ic", "Run conversion", class = "btn-success"),
          span(class = "note",
               "The equivalent call is written to the R script either way, ",
               "so you can run it outside the app if the ICES packages are ",
               "not installed here."))),

      column(4,
        h4("Call"),
        verbatimTextOutput("ic_call"),
        h4("Status"),
        uiOutput("ic_status"),
        h4("Result"),
        uiOutput("ic_result"))),
    fluidRow(column(12, h4("catches preview"), DTOutput("ic_catches"))))
}
