#' Emit the script header
#'
#' @param file_name The catch file the session read.
#' @param stock The stock code.
#' @param n_rows Row count of the catch table.
#' @return A character vector of R code.
#' @export
emit_header <- function(file_name, stock, n_rows) {
  c("## ===========================================================",
    "## Discard raising setup - generated by the discard explorer",
    sprintf("## Generated : %s", format(Sys.time(), "%Y-%m-%d %H:%M:%S")),
    sprintf("## Source    : %s", file_name),
    sprintf("## Stock     : %s", paste(stock, collapse = ", ")),
    sprintf("## Rows      : %s", n_rows),
    "## ===========================================================",
    "library(dplyr); library(rlang)",
    "")
}

#' Emit the code that reads the catch file
#'
#' @param file_name The catch file to read.
#' @param sep Field separator.
#' @param stock,year Optional stock and year filters.
#' @param dims The stratum dimensions.
#' @param dr_min,dr_max Donor discard-rate window.
#' @param dir The folder the tables were read from, emitted as `cef_dir`
#'   so the script runs from anywhere. `NA` for an upload, where there is
#'   no path worth recording.
#' @param dist_file,eff_file The companion tables, when they were loaded.
#' @return A character vector of R code.
#' @export
emit_load_code <- function(file_name, sep = ",", stock = NULL, year = NULL,
                          dims = NULL, dr_min = NA, dr_max = NA,
                          dir = NA_character_, dist_file = NA_character_,
                          eff_file = NA_character_) {
  sep_txt <- switch(sep, "," = '","', ";" = '";"', "\t" = '"\\t"', '","')
  # The folder the tables were pointed at is part of the analysis. Without
  # it the script says read.csv("catches_CEF_v17.1.csv") and only runs if
  # the reader happens to have set the same working directory - which is
  # exactly the thing a reproducible script is supposed to remove.
  # file.path(cef_dir, ...) makes the location one line to change.
  has_dir <- !is.na(dir) && nzchar(dir)
  rd <- function(obj, fn) sprintf(
    '%s <- read.csv(%s, sep = %s, stringsAsFactors = FALSE)', obj,
    if (has_dir) sprintf('file.path(cef_dir, "%s")', fn) else sprintf('"%s"', fn),
    sep_txt)
  c("## ---- Load ------------------------------------------------",
    if (has_dir) c(
      "## The folder the CEF tables were read from. Change this one line",
      "## to re-run the analysis against another copy of the data.",
      sprintf('cef_dir <- "%s"', gsub("\\\\", "/", dir)),
      ""),
    rd("catch_data", file_name),
    if (!is.na(dist_file) && nzchar(dist_file)) rd("distributions", dist_file),
    if (!is.na(eff_file) && nzchar(eff_file)) rd("effort", eff_file),
    "")
}

#' Emit the filtering and stratum-building code
#'
#' @param stock,year Optional stock and year filters.
#' @param dims The stratum dimensions.
#' @param dr_min,dr_max Donor discard-rate window.
#' @return A character vector of R code.
#' @export
emit_filter_code <- function(stock = NULL, year = NULL, dims = NULL,
                             dr_min = NA, dr_max = NA) {
  out <- c("## ---- Filter and build strata -------------------------------")
  if (!is.null(stock) && nzchar(stock))
    out <- c(out, sprintf('catch_data <- catch_data %%>%% filter(stock == "%s")', stock))
  if (!is.null(year) && nzchar(year))
    out <- c(out, sprintf('catch_data <- catch_data %%>%% filter(year == %s)', year))
  if (!is.null(dims))
    out <- c(out,
      "",
      sprintf("dims <- %s", fmt_vals(dims)),
      "strata <- catch_data %>%",
      '    filter(catchCategory == "Lan") %>%',
      "    group_by(across(all_of(dims))) %>%",
      "    summarise(landings = sum(total, na.rm = TRUE),",
      "              landings_with_discards = sum(",
      "                  total[!is.na(domainCatchDis) & domainCatchDis != \"\"],",
      "                  na.rm = TRUE), .groups = \"drop\") %>%",
      "    full_join(catch_data %>%",
      '                  filter(catchCategory != "Lan") %>%',
      "                  group_by(across(all_of(dims))) %>%",
      '                  summarise(discards = sum(total, na.rm = TRUE),',
      '                            .groups = "drop"), by = dims) %>%',
      "    mutate(across(c(landings, landings_with_discards, discards),",
      "                  ~ ifelse(is.na(.x), 0, .x)),",
      "           coverage = ifelse(landings > 0,",
      "                             landings_with_discards / landings * 100, NA),",
      "           discard_rate = ifelse(landings_with_discards + discards > 0,",
      "                                 discards / (landings_with_discards + discards),",
      "                                 NA),",
      '           stratum_id = do.call(paste, c(across(all_of(dims)), sep = " | ")))')
  if (!is.na(dr_min) || !is.na(dr_max)) {
    cnd <- c(if (!is.na(dr_min)) sprintf("discard_rate >= %s", dr_min),
             if (!is.na(dr_max)) sprintf("discard_rate <= %s", dr_max))
    out <- c(out, "",
      "## Strata excluded from donor pools (outlying discard rates):",
      sprintf("strata$donor_ok <- is.na(strata$discard_rate) | (%s)",
              paste(cnd, collapse = " & ")))
  }
  c(out, "")
}

#' Emit the field-derivation code
#'
#' Writes out the derivation explicitly, rather than a call to
#' [derive_fields()], so the reader can see exactly how the metier and ICES
#' area levels are split and change it if their stock needs something else.
#'
#' @return A character vector of R code.
#' @seealso [derive_fields()], [emit_area_helper()]
#' @export
emit_derive_code <- function() {
  c("## ---- Derived fields ---------------------------------------",
    "catch_data <- catch_data %>%",
    "    mutate(Country = vesselFlagCountry,",
    "           Season  = seasonValue,",
    "           metier4 = sub('^([^_]+).*$', '\\\\1', fleetValue),",
    "           metier5 = sub('^([^_]+_[^_]+).*$', '\\\\1', fleetValue),",
    "           metier6 = sub('^([^_]+_[^_]+_[^_]+).*$', '\\\\1', fleetValue),",
    "           gear    = metier4,",
    "           target  = sub('^[^_]+_([^_]+).*$', '\\\\1', fleetValue),",
    "           mesh    = sub('^[^_]+_[^_]+_([^_]+).*$', '\\\\1', fleetValue),",
    "           ## the ICES area code is a nested path, so it is split into",
    "           ## its three levels. A code already coarser than the level",
    "           ## asked for repeats rather than becoming NA: 27.4 IS its own",
    "           ## division and subdivision as far as the data goes.",
    "           ICESSubArea     = .ices_lvl(areaValue, 2),   ## 27.X",
    "           ICESDivision    = .ices_lvl(areaValue, 3),   ## 27.X.X",
    "           ICESSubdivision = .ices_lvl(areaValue, 4))   ## 27.X.X.X",
    "")
}

#' Emit the ICES area-splitting helper used by the derived code
#'
#' @return A character vector of R code.
#' @seealso [emit_derive_code()]
#' @export
emit_area_helper <- function() c(
  "## ---- ICES area levels -------------------------------------",
  ".ices_lvl <- function(area, n) {",
  "    p <- strsplit(as.character(area), '.', fixed = TRUE)",
  "    out <- vapply(p, function(z)",
  "        if (!length(z)) NA_character_",
  "        else paste(z[seq_len(min(n, length(z)))], collapse = '.'),",
  "        character(1))",
  "    out[is.na(area) | !nzchar(as.character(area))] <- NA_character_",
  "    out",
  "}",
  "")

#' Emit the named value sets a rule set refers to
#'
#' @param sets Named list of value sets.
#' @return A character vector of R code.
#' @export
emit_sets_code <- function(sets) {
  if (!length(sets)) return(character(0))
  c("## ---- Reusable value sets ----------------------------------",
    vapply(names(sets), function(n)
      sprintf("%s <- %s", n, fmt_vals(sets[[n]])), character(1)),
    "")
}

