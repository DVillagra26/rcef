#' Emit the automatic grouping as a reusable rule
#'
#' Writes the hierarchy and thresholds that were used, not the group membership
#' they produced, so re-running on new data reapplies the policy.
#'
#' @param rec Output of [recommend_raising()].
#' @param hierarchy Key columns, finest first.
#' @param thresholds One threshold, or one per level.
#' @param direction Retained for older saved scenarios.
#' @param dims The stratum dimensions.
#' @return A character vector of R code.
#' @seealso [recommend_raising()], [emit_rules_code()]
#' @export
emit_hier_code <- function(rec, hierarchy, thresholds, direction, dims,
                           self_threshold = NA, donor_cov_min = NA,
                           donor_meas_min = NA, donor_excluded = character(0)) {
  grp <- raising_groups(rec)
  # map each group back to the strata it covers
  sid <- split(rec$stratum_id, match(rec$raise_condition, grp$raise_condition))

  mk <- function(txts) vapply(seq_along(txts), function(i)
    sprintf("    %s = quo(%s)%s", grp$group_id[i], txts[i],
            if (i < length(txts)) "," else ""), character(1))

  strata_txt <- vapply(seq_len(nrow(grp)), function(i) {
    ids <- sid[[as.character(i)]]
    wrap_lines(sprintf("stratum_id %%in%% %s", fmt_vals(ids)), width = 68)
  }, character(1))

  donor_txt <- vapply(seq_len(nrow(grp)), function(i) {
    cn <- grp$raise_condition[i]
    if (cn == "TRUE") "TRUE"
    else if (cn == "(none needed)") "FALSE   ## fully sampled, nothing to raise"
    else wrap_lines(cn, width = 68)
  }, character(1))

  # The RECIPE the app ran, not just the groups it produced. For the
  # automated method the hierarchy, the per-level thresholds (own stratum
  # included) and any donor exclusion ARE the decision; recommend_raising()
  # turns them into strataCond / matchedDataCond. Showing the call means a
  # reviewer can re-run it, change one threshold and see the effect -
  # which a frozen list of resolved groups does not allow.
  excl_arg <- if (length(donor_excluded))
    sprintf(",\n                donor_excluded = %s", fmt_vals(donor_excluded)) else ""
  cov_arg  <- if (!is.na(donor_cov_min))
    sprintf(",\n                donor_cov_min = %s", donor_cov_min) else ""
  meas_arg <- if (!is.na(donor_meas_min))
    sprintf(",\n                donor_meas_min = %s", donor_meas_min) else ""
  self_arg <- if (!is.na(self_threshold))
    sprintf("%s", self_threshold) else "NA"

  c("## ===========================================================",
    "## Approach A - hierarchical recommendation",
    "##",
    "## The recipe is the decision: the hierarchy, the threshold each",
    "## pool must clear (own-stratum threshold first, then one per key),",
    "## and any donor excluded by coverage, measurements or discard rate.",
    "## recommend_raising() turns this into the two condition lists below.",
    sprintf("## Strata defined by : %s", paste(dims, collapse = ", ")),
    sprintf("## Hierarchy         : %s", paste(hierarchy, collapse = " > ")),
    sprintf("## Own-stratum bar   : %s%%", self_arg),
    sprintf("## Pool thresholds   : %s%%", paste(thresholds, collapse = ", ")),
    if (!is.na(donor_cov_min))
      sprintf("## Donor coverage min: %s%%", donor_cov_min),
    if (!is.na(donor_meas_min))
      sprintf("## Donor measurements: %s", donor_meas_min),
    if (length(donor_excluded))
      sprintf("## Donors excluded   : %d stratum/strata by hand",
              length(donor_excluded)),
    "## ===========================================================",
    "",
    "## Build the strata table, classify it, and recommend the raising:",
    sprintf("strata <- classify_strata(build_strata(catch_data, %s), threshold = %s)",
            fmt_vals(dims), self_arg),
    "rec <- recommend_raising(",
    sprintf("  strata, hierarchy = %s,", fmt_vals(hierarchy)),
    sprintf("  thresholds = c(%s, %s),   # own-stratum bar, then one per key",
            self_arg, fmt_num(thresholds)),
    sprintf("  dims = %s%s%s%s)", fmt_vals(dims), cov_arg, meas_arg, excl_arg),
    "",
    "## recommend_raising() resolves the recipe into these two lists:",
    "conds <- conds_from_auto(rec)   # $strataCond and $matchedDataCond",
    "",
    "## For reference, the groups it resolved to:",
    "## Strata to be raised, by group:",
    "strataCond <- list(", mk(strata_txt), ")",
    "",
    "## Data used to raise each group:",
    "matchedDataCond <- list(", mk(donor_txt), ")",
    "",
    "## Level reached per group:",
    paste0("##   ", grp$group_id, " : ", grp$raise_level,
           "  (", grp$n_strata, " strata)"),
    "")
}

#' Emit a manual rule set
#'
#' @param rules The rule list.
#' @param sets Named value sets referenced by the rules.
#' @param dims The stratum dimensions.
#' @return A character vector of R code.
#' @seealso [new_rule()], [emit_hier_code()]
#' @export
emit_rules_code <- function(rules, sets, dims = NULL) {
  # The raise side is taken from conds_from_rules(), NOT from each rule's
  # own clause. "First match wins" is how the app evaluates the rules, but
  # catchRaising() does not evaluate them in order - it treats the strata
  # conditions as a partition and applies each independently. Writing the
  # bare clauses here produced a script in which every rule an earlier rule
  # had already claimed was raised a second time, silently inflating the
  # discards; worst on a catch-all, whose bare clause is TRUE and so would
  # re-raise the entire stock.
  #
  # conds_from_rules() makes the complements explicit, so the emitted
  # conditions are a genuine partition and the script reproduces what the
  # app did. The donor side is deliberately NOT complemented: a stratum
  # that has already donated to one group may donate to another, and only
  # the raised side has to be exclusive.
  cd <- conds_from_rules(rules, sets, dims)
  mk <- function(side) {
    l <- if (side == "source") cd$matchedDataCond else cd$strataCond
    vapply(seq_along(rules), function(i) {
      cnd <- if (side == "source")
        # the donor side must carry the named-stratum exclusion too, which
        # needs the dimension names to build its key
        source_cond_string(rules[[i]], dims)
      else rlang::quo_text(l[[i]])
      lbl <- rules[[i]]$label
      sprintf("    %s%s = quo(%s)%s",
              ifelse(nzchar(lbl), paste0("## ", lbl, "\n    "), ""),
              rules[[i]]$id, wrap_lines(cnd),
              if (i < length(rules)) "," else "")
    }, character(1))
  }
  c(emit_sets_code(sets),
    "## ===========================================================",
    "## Approach B - manual group definitions",
    "## Rules are evaluated IN ORDER; first match wins. catchRaising()",
    "## has no notion of order, so that is written into the conditions:",
    "## each rule's strataCond is its own clause MINUS everything above",
    "## it, which makes the set a partition and stops any stratum being",
    "## raised twice.",
    "##",
    "## matchedDataCond carries no such complement, on purpose - a donor",
    "## can feed several groups, only a raised stratum is exclusive.",
    "## ===========================================================",
    "## Strata to be raised:",
    "strataCond <- list(", mk("raise"), ")",
    "",
    "## Data used to raise them:",
    "matchedDataCond <- list(", mk("source"), ")",
    "")
}

