# ============================================================
#  0_Functions_emit.R
#  Emit the R script that reproduces a session.
# ------------------------------------------------------------
#  Every function here returns CHARACTER VECTORS of R code; none of them
#  evaluates anything. The app assembles them into the script shown on the
#  "5. R script" tab, so a session can be replayed - or next year's assessment
#  re-run - outside the app entirely.
#
#  The emitted script deliberately mirrors the package API rather than the
#  app's internals: derive_fields(), build_strata(), classify_strata(), the
#  group definition, then catchRaising() or catchAllocationAoL(). What the
#  reader gets is a plain analysis script, not a transcript of button presses.
#
#  Automatic groupings are emitted as RULES rather than as the resulting group
#  membership, so re-running on next year's data reapplies the POLICY instead
#  of replaying this year's strata.
#
#  DEPENDENCIES  Imports: none beyond base R (string building only).
# ============================================================

# ----------------------------------------------------------
#  Formatting
# ----------------------------------------------------------

#' Wrap a long emitted line to a readable width
#'
#' @param x The line to wrap.
#' @param width Target width in characters.
#' @param indent Indent applied to continuation lines.
#' @return A character vector of wrapped lines.
#' @keywords internal
#' @noRd
#' @export
wrap_lines <- function(x, width = 74, indent = "         ") {
  if (nchar(x) <= width) return(x)
  parts <- strsplit(x, " & ", fixed = TRUE)[[1]]
  out <- character(0); cur <- parts[1]
  for (p in parts[-1]) {
    if (nchar(cur) + nchar(p) + 3 > width) { out <- c(out, cur); cur <- p }
    else cur <- paste(cur, p, sep = " & ")
  }
  paste(c(out, cur), collapse = paste0(" &\n", indent))
}

